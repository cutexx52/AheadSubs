"""Generate Wiki navigation from reviewed README sections; no credentials required."""
import argparse
import json
from pathlib import Path
import re
from urllib.parse import quote, unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
LINK = re.compile(r'(!?)\[([^\]]*)\]\(([^)]+)\)')


def section(text, name):
    start, end = f'<!-- wiki:{name}:start -->', f'<!-- wiki:{name}:end -->'
    if text.count(start) != 1 or text.count(end) != 1:
        raise ValueError(f'Expected one {name} marker pair')
    before, rest = text.split(start)
    if end in before:
        raise ValueError(f'Reversed {name} markers')
    return rest.split(end)[0].strip()


def pages(root=ROOT, repository='cutexx52/AheadSubs'):
    if not re.fullmatch(r'[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+', repository):
        raise ValueError('Invalid GitHub repository')
    base = f'https://github.com/{repository}'
    manifest = json.loads((root / 'docs/images/manifest.json').read_text(encoding='utf-8'))
    images = {}
    for item in manifest['images']:
        if item['contains_text']:
            for language in ('english', 'chinese'):
                images[item[language]] = language
        else:
            images[item['shared']] = 'shared'
    output = {}
    for suffix, language in (('', 'english'), ('.zh-CN', 'chinese')):
        readme = (root / f'README{suffix}.md').read_text(encoding='utf-8')
        content = section(readme, 'intro') + '\n\n' + section(readme, 'navigation')

        def rewrite(match):
            image, label, target = match.groups()
            parsed = urlsplit(target)
            if parsed.scheme or parsed.netloc:
                if parsed.scheme not in ('https', 'http') or image:
                    raise ValueError(f'Unsupported external link/image: {target}')
                return match[0]
            path = unquote(parsed.path)
            resolved = (root / path).resolve()
            if not path or not resolved.is_relative_to(root.resolve()) or not resolved.is_file():
                raise ValueError(f'Broken repository link: {target}')
            if image:
                if not label.strip() or images.get(path) not in (language, 'shared'):
                    raise ValueError(f'Image must have alt text and match {language}: {path}')
                url = f'https://raw.githubusercontent.com/{repository}/main/{quote(path)}'
            elif path in ('README.md', 'README.zh-CN.md') and not parsed.fragment:
                # Only the language switch targets Wiki pages. Quick-start links carry anchors.
                url = f'{base}/wiki/Home' + ('.zh-CN' if '.zh-CN' in path else '')
            else:
                if path.endswith('.md') and ('.zh-CN.md' in path) != bool(suffix):
                    raise ValueError(f'Wrong language document: {path}')
                url = f'{base}/blob/main/{quote(path)}'
                if parsed.fragment:
                    url += '#' + parsed.fragment
            return f'{image}[{label}]({url})'

        content = LINK.sub(rewrite, content)
        notice = ('自动生成；请通过主仓库 PR 修改 README 中的 Wiki 区段。'
                  if suffix else 'Generated page; edit the README Wiki sections through a main-repository PR.')
        output[f'Home{suffix}.md'] = f'<!-- Generated by tools/wiki.py; do not edit here. -->\n\n{content}\n\n{notice}\n'
    return output


def write_pages(output, destination):
    destination.mkdir(parents=True, exist_ok=True)
    changed = []
    for name, content in output.items():
        target = destination / name
        if not target.is_file() or target.read_text(encoding='utf-8') != content:
            target.write_text(content, encoding='utf-8', newline='\n')
            changed.append(name)
    return changed


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--repository', default='cutexx52/AheadSubs')
    args = parser.parse_args()
    generated = pages(repository=args.repository)
    if args.output:
        print('Updated: ' + ', '.join(write_pages(generated, args.output)))
    else:
        print('Both Wiki pages, repository links and image languages validated')
